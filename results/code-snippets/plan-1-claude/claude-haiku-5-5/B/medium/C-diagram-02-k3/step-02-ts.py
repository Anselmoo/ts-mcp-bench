# ---------- determinant basis
dets = list(itertools.combinations(range(10), 4))
index = {d: n for n, d in enumerate(dets)}
N = len(dets)

def annih(i, st):
    if i not in st: return None
    p = st.index(i)
    return (-1)**p, st[:p]+st[p+1:]
def create(i, st):
    if i in st: return None
    p = sum(1 for x in st if x < i)
    return (-1)**p, tuple(sorted(st+(i,)))

def apply_c(i, j, st):  # c_i^dag c_j
    r = annih(j, st)
    if r is None: return None
    s1, t = r
    r2 = create(i, t)
    if r2 is None: return None
    return s1*r2[0], r2[1]

H_ee = np.zeros((N, N))
nz = [(i,j,k,l) for i,j,k,l in itertools.product(range(10), repeat=4) if abs(V[i,j,k,l])>1e-12]
for n, st in enumerate(dets):
    for (i,j,k,l) in nz:
        # c_i^dag c_j^dag c_l c_k |st>
        r = annih(k, st)
        if r is None: continue
        s1, t1 = r
        r = annih(l, t1)
        if r is None: continue
        s2, t2 = r
        r = create(j, t2)
        if r is None: continue
        s3, t3 = r
        r = create(i, t3)
        if r is None: continue
        s4, t4 = r
        H_ee[index[t4], n] += 0.5*V[i,j,k,l]*s1*s2*s3*s4

# one-body diagonal part: energies per orbital (eg: dz2, dx2-y2 -> +6Dq ; t2g -> -4Dq)
orb_eg = np.array([1,0,0,0,0])  # for each orbital, 1 if eg
def one_body_diag(Dq):
    d = np.zeros(N)
    for n, st in enumerate(dets):
        e = 0.0
        for s in st:
            a = s//2
            e += 6*Dq if a in (0,1) else -4*Dq
        d[n] = e
    return d

# ---------- spin operators
def spin_ops():
    Sz = np.zeros((N,N)); Sp = np.zeros((N,N))
    for n, st in enumerate(dets):
        nup = sum(1 for s in st if s%2==0); ndn = 4-nup
        Sz[n,n] = 0.5*(nup-ndn)
        for a in range(5):
            r = apply_c(2*a, 2*a+1, st)   # c_up^dag c_dn  = S+
            if r is not None:
                Sp[index[r[1]], n] += r[0]
    Sm = Sp.T
    S2 = Sz@Sz + 0.5*(Sp@Sm + Sm@Sp)
    return S2
S2 = spin_ops()

# ---------- group: 24 rotations generated by C4z and C3(111)
C4 = np.array([[0,-1,0],[1,0,0],[0,0,1.]])
C3 = np.array([[0,1,0],[0,0,1],[1,0,0.]])
def key(R): return tuple(np.round(R,6).ravel())
grp = {key(np.eye(3)): np.eye(3)}
frontier = [np.eye(3)]
while frontier:
    new = []
    for R in frontier:
        for g in (C4, C3):
            Rn = g@R
            if key(Rn) not in grp:
                grp[key(Rn)] = Rn; new.append(Rn)
    frontier = new
G24 = list(grp.values())
assert len(G24) == 24, len(G24)

def Dmat(R):
    Rinv = R.T
    Xt = P @ Rinv.T   # rows: R^{-1} x  (x as row vectors: (R^{-1} x)^T = x^T R^{-T}... )
    Fr = dfuncs(Xt)/norm
    # D_ab = <f_a, T f_b>, T f(x)=f(R^-1 x)
    return (Fv*W[:,None]).T @ Fr

def classify(R):
    tr = np.trace(R)
    if abs(tr-3)<1e-6: return 'E'
    if abs(tr)<1e-6: return 'C3'
    if abs(tr+1)<1e-6:
        diag = np.allclose(R, np.diag(np.diag(R)))
        return 'C2' if diag else "C2'"
    if abs(tr-1)<1e-6: return 'C4'
    raise ValueError

