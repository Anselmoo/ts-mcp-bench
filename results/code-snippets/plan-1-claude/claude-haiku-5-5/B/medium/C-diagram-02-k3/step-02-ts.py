import numpy as np, itertools, math
from numpy.polynomial.legendre import leggauss

# ---------- angular grid & real d functions (harmonic polynomials on unit sphere)
nt, nph = 16, 32
xg, wg = leggauss(nt)
ph = np.arange(nph)*2*np.pi/nph; wph = np.full(nph, 2*np.pi/nph)
ct, PH = np.meshgrid(xg, ph, indexing='ij'); W = (np.outer(wg, wph)).ravel()
st = np.sqrt(1-ct**2)
P = np.stack([st*np.cos(PH), st*np.sin(PH), ct], -1).reshape(-1, 3)  # unit vectors

def dfuncs(X):
    x, y, z = X[:,0], X[:,1], X[:,2]
    return np.stack([3*z*z-1, x*x-y*y, x*y, x*z, y*z], 1)  # r=1
Fv = dfuncs(P)
norm = np.sqrt(W @ (Fv**2))
Fv = Fv/norm   # orthonormal on sphere, columns = orbitals (dz2, dx2-y2, dxy, dxz, dyz)

# ---------- Coulomb angular coefficients a_k
def legendre(k, x):
    return np.polynomial.legendre.Legendre.basis(k)(x)
cosg = P @ P.T
G = {}
for k in (0, 2, 4):
    Pk = legendre(k, cosg)
    # g[(a,c)](Omega) = f_a f_c
    ac = [(a, c) for a in range(5) for c in range(5)]
    g = np.array([Fv[:, a]*Fv[:, c] for a, c in ac])          # (25, N)
    M = (g*W) @ Pk @ (g*W).T                                    # (25,25)
    G[k] = (ac, M)

def angular(k, a, c, b, d):
    ac, M = G[k]
    return M[a*5+c, b*5+d]

# ---------- two-electron integrals in spin-orbital basis
# spin-orbital index i = 2*orb + s
F2 = None
def build_V(F):
    V = np.zeros((10,10,10,10))
    for i in range(10):
        for j in range(10):
            for kk in range(10):
                for l in range(10):
                    si, sj, sk, sl = i%2, j%2, kk%2, l%2
                    if si != sk or sj != sl: continue
                    a, b, c, d = i//2, j//2, kk//2, l//2
                    val = 0.0
                    for k in (0, 2, 4):
                        val += F[k]*angular(k, a, c, b, d)
                    V[i,j,kk,l] = val
    return V

