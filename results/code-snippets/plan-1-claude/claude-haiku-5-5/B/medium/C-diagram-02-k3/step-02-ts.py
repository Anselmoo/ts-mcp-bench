# ---------- spectra per irrep
def levels_for(Dq):
    Hd = H_ee + np.diag(one_body_diag(Dq))
    out = []
    for irr in ['A1','A2','E','T1','T2']:
        Pm = Pr[irr]
        w, vec = np.linalg.eigh((Pm+Pm.T)/2)
        Q = vec[:, w > 0.5]
        if Q.shape[1] == 0: continue
        Hr = Q.T@Hd@Q; S2r = Q.T@S2@Q
        M = Hr + 1000.0*S2r
        ev, U = np.linalg.eigh((M+M.T)/2)
        d = dimI[irr]
        Ens = []
        for k in range(len(ev)):
            v = U[:,k]
            E = v@Hr@v; s2 = v@S2r@v
            S = (-1+math.sqrt(1+4*s2))/2
            Ens.append((round(S*2)/2, E))
        # group
        from collections import Counter
        cnt = Counter()
        for S, E in Ens:
            cnt[(S, round(E, 6))] += 1
        for (S, E), m in cnt.items():
            mult = int(round(2*S+1))*d
            nlev = m/mult
            assert abs(nlev-round(nlev)) < 1e-9, (irr, S, E, m)
            name = {'A1':'A1g','A2':'A2g','E':'Eg','T1':'T1g','T2':'T2g'}[irr]
            for _ in range(int(round(nlev))):
                out.append((E, f"{int(round(2*S+1))}{name}"))
    out.sort()
    return out

