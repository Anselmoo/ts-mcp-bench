def Dmat(R):
    Fr = dfuncs(P @ R)/norm     # f(R^{-1} x) with R^{-1}=R^T: (R^T x)^T = x^T R
    return (Fv*W[:,None]).T @ Fr

def classify(R):
    tr = round(np.trace(R))
    if tr == 3: return 'E'
    if tr == 0: return 'C3'
    if tr == -1: return 'C2' if np.allclose(R, np.diag(np.diag(R))) else "C2'"
    if tr == 1: return 'C4'
    raise ValueError(tr)

