def annih(i, s):
    if i not in s: return None
    p = s.index(i); return (-1)**p, s[:p]+s[p+1:]
def create(i, s):
    if i in s: return None
    p = sum(1 for x in s if x < i); return (-1)**p, tuple(sorted(s+(i,)))

nz = [(i,j,k,l) for i,j,k,l in itertools.product(range(10), repeat=4) if abs(V[i,j,k,l])>1e-12]
