ac = [(a, c) for a in range(5) for c in range(5)]
for k in (0, 2, 4):
    Pk = legendre(k, cosg)
    g = np.array([Fv[:, a]*Fv[:, c] for a, c in ac])
    G[k] = (g*W) @ Pk @ (g*W).T   # index (a*5+c, b*5+d)

