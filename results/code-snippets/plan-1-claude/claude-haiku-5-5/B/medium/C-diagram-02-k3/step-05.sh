from numpy.polynomial.legendre import leggauss
from collections import Counter

nt, nph = 16, 32
xg, wg = leggauss(nt)
ph = np.arange(nph)*2*np.pi/nph; wph = np.full(nph, 2*np.pi/nph)
ct, PH = np.meshgrid(xg, ph, indexing='ij'); W = (np.outer(wg, wph)).ravel()
st = np.sqrt(1-ct**2)
P = np.stack([st*np.cos(PH), st*np.sin(PH), ct], -1).reshape(-1, 3)

def dfuncs(X):
    x, y, z = X[:,0], X[:,1], X[:,2]
    return np.stack([3*z*z-(x*x+y*y+z*z), x*x-y*y, x*y, x*z, y*z], 1)
Fv0 = dfuncs(P)
norm = np.sqrt(W @ (Fv0**2))
Fv = Fv0/norm

cosg = P @ P.T
def legendre(k, x):
    return np.polynomial.legendre.Legendre.basis(k)(x)
