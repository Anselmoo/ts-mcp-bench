        s2, t = r; r = create(j, t)
        if r is None: continue
        s3, t = r; r = create(i, t)
        if r is None: continue
        s4, t = r
        H_ee[index[t], n] += 0.5*V[i,j,k,l]*s1*s2*s3*s4

# spin operators
